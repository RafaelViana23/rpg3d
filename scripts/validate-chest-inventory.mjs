import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundle=await build({stdin:{contents:"export {transferChestItem} from './src/inventory/ChestInventory';",resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'esm'});
const {transferChestItem}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
let state={quantities:{'tunic':1,'hp-potion':3}};
assert.equal(transferChestItem(state,'inn-room-1','tunic',true),true);
assert.equal(state.quantities.tunic,0);
assert.equal(transferChestItem(state,'inn-room-1','tunic',true),false);
assert.equal(transferChestItem(state,'inn-room-2','tunic',false),false);
assert.equal(transferChestItem(state,'inn-room-1','invalid',true),false);
state=JSON.parse(JSON.stringify(state));
assert.equal(transferChestItem(state,'inn-room-1','tunic',false),true);
assert.equal(state.quantities.tunic,1);
assert.equal(transferChestItem(state,'inn-room-1','tunic',false),false);
assert.equal(transferChestItem(state,'palace','hp-potion',true),true);
assert.equal(state.quantities['hp-potion'],2);
assert.equal(state.chestInventories.palace['hp-potion'],1);
assert.equal(state.chestInventories['inn-room-1']['hp-potion'],undefined);
console.log('Transfers conserve quantities, reject empty sources, preserve zero counts and persist independent chests.');
